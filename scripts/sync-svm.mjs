// Copies the API's clause SVM trainer into src/features/account/svm/ for the Settings → Train model worker, so the UI
// builds on its own (e.g. `vercel deploy` from UI/, where ../API isn't uploaded). Runs before dev/build/typecheck;
// when ../API is missing it keeps the committed copies. Edit the API files, not the copies.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ui = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(ui, '../API/supabase/functions/api/lib');
const dest = join(ui, 'src/features/account/svm');
const files = ['clause-svm-train.ts', 'clause-svm-features.ts'];

if (!existsSync(src)) {
  console.log('sync-svm: ../API not found, using the committed copies');
} else {
  mkdirSync(dest, { recursive: true });
  for (const file of files) {
    const header = `// GENERATED by UI/scripts/sync-svm.mjs from API/supabase/functions/api/lib/${file}. Do not edit.\n`;
    const out = join(dest, file);
    const next = header + readFileSync(join(src, file), 'utf8');
    if (!existsSync(out) || readFileSync(out, 'utf8') !== next) writeFileSync(out, next);
  }
}
